"""Заземляющие завершения (§3.3, §3.4 MASTER-PLAN).

ВСЕГДА завершают вечерний и ситуативный чек-ин — заземлением, не вопросом.
Не оставлять с открытой раной (§5.1).
"""

from __future__ import annotations

import random

# Завершение вечера (§3.3)
EVENING_GROUNDING = [
    "На сегодня достаточно. Ты это заметил — этого хватит.\nОдин медленный вдох — и закрываем день.",
    "Хватит на сегодня. Ты отметил — этого достаточно.\nМедленный вдох — и день закрыт.",
    "На сегодня всё. Ты заметил — и довольно.\nОдин спокойный вдох, и отпускаем.",
]

# Завершение ситуативного (§3.4)
SITUATIONAL_GROUNDING = [
    "Заметил. Это сигнал, не факт. Один медленный вдох.",
    "Отметил. Это сигнал, не приговор. Вдох — медленно.",
    "Заметил это. Сигнал, не факт. Сделай один медленный вдох.",
]

# Приглашение «на сегодня хватит» (кнопка завершения вечера до deep)
ENOUGH_FOR_TODAY = [
    "Хорошо. На сегодня достаточно.",
    "Ок, закрываем на этом.",
]


def evening() -> str:
    return random.choice(EVENING_GROUNDING)


def situational() -> str:
    return random.choice(SITUATIONAL_GROUNDING)


def enough() -> str:
    return random.choice(ENOUGH_FOR_TODAY)
